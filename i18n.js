const LANGS = ["zh", "en", "ja"];
const LANG_ATTR = { zh: "zh-CN", en: "en", ja: "ja" };

function detectLang() {
  const params = new URLSearchParams(location.search);
  const fromQuery = params.get("lang");
  if (LANGS.includes(fromQuery)) return fromQuery;
  const saved = localStorage.getItem("tbshare-lang");
  if (LANGS.includes(saved)) return saved;
  const nav = (navigator.language || "zh").toLowerCase();
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("en")) return "en";
  return "zh";
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.zh;
  document.documentElement.lang = LANG_ATTR[lang] || "zh-CN";
  document.title = dict["meta.title"];
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", dict["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (dict[key] != null) el.setAttribute("alt", dict[key]);
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });

  localStorage.setItem("tbshare-lang", lang);
  const url = new URL(location.href);
  url.searchParams.set("lang", lang);
  history.replaceState(null, "", url);
}

function initI18n() {
  const lang = detectLang();
  applyLang(lang);
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initI18n();
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) entry.target.classList.add("in");
      });
    },
    { threshold: 0.12 }
  );
  document.querySelectorAll(".section, .hero-copy, .hero-visual, .voice-card").forEach((el) => {
    el.classList.add("reveal");
    observer.observe(el);
  });
});
